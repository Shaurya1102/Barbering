CREATE TABLE barber_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    bio VARCHAR(2000),
    city VARCHAR(120),
    region VARCHAR(120),
    street_address VARCHAR(255),
    postal_code VARCHAR(32),
    country VARCHAR(120),
    timezone_id VARCHAR(80) NOT NULL DEFAULT 'UTC',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE barber_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id) ON DELETE CASCADE,
    service_id BIGINT NOT NULL REFERENCES services (id),
    price_amount NUMERIC(10, 2) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_barber_services_profile_service UNIQUE (barber_profile_id, service_id),
    CONSTRAINT ck_barber_services_price CHECK (price_amount >= 0),
    CONSTRAINT ck_barber_services_duration CHECK (duration_minutes BETWEEN 5 AND 480)
);

CREATE TABLE working_hours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_working_hours_profile_day UNIQUE (barber_profile_id, day_of_week),
    CONSTRAINT ck_working_hours_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_working_hours_range CHECK (start_time < end_time)
);

CREATE TABLE barber_breaks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    reason VARCHAR(120),
    CONSTRAINT ck_barber_breaks_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_barber_breaks_range CHECK (start_time < end_time)
);

CREATE TABLE barber_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id) ON DELETE CASCADE,
    storage_key VARCHAR(36) NOT NULL UNIQUE,
    content_type VARCHAR(40) NOT NULL,
    size_bytes BIGINT NOT NULL,
    alt_text VARCHAR(160),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_barber_photos_size CHECK (size_bytes BETWEEN 1 AND 5242880)
);

CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users (id),
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id),
    barber_service_id BIGINT NOT NULL REFERENCES barber_services (id),
    service_name_snapshot VARCHAR(100) NOT NULL,
    price_amount NUMERIC(10, 2) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    customer_note VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_appointments_range CHECK (start_at < end_at),
    CONSTRAINT ck_appointments_status CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED', 'COMPLETED', 'NO_SHOW'))
);

CREATE INDEX idx_appointments_barber_start ON appointments (barber_profile_id, start_at);
CREATE INDEX idx_appointments_customer_start ON appointments (customer_id, start_at);
CREATE INDEX idx_barber_services_enabled ON barber_services (barber_profile_id, enabled);
CREATE INDEX idx_barber_profiles_city ON barber_profiles (city);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE REFERENCES appointments (id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES users (id),
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id),
    rating SMALLINT NOT NULL,
    review_text VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_reviews_barber_created ON reviews (barber_profile_id, created_at DESC);

CREATE TABLE favourites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    barber_profile_id BIGINT NOT NULL REFERENCES barber_profiles (id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_favourites_customer_barber UNIQUE (customer_id, barber_profile_id)
);
